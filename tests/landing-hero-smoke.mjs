import assert from "node:assert/strict";

const origin = process.env.SASSY_TEST_URL ?? "http://localhost:3000";
const page = await fetch(origin);
assert.equal(page.status, 200, "Beranda harus bisa dibuka tanpa login");
const html = await page.text();
assert.match(html, /Pengukusan lebih/);
assert.match(html, /login-hero\.webp/);
assert.match(html, /href="\/login"/);
assert.equal((html.match(/data-hero-badge/g) ?? []).length, 3, "Tiga badge alat tersedia");
assert.match(html, /Pemantauan suhu/);
assert.match(html, /Kendali burner/);
assert.match(html, /Level air terpantau/);
assert.match(html, /id="tentang"/);
assert.match(html, /Satu alat\. Proses yang bisa/);
assert.match(html, /visual perangkat sementara/);
assert.ok(html.indexOf("Pengukusan lebih") < html.indexOf("Satu alat. Proses yang bisa"), "About mengikuti hero");
assert.match(html, /id="skema"/);
assert.match(html, /ESP32-S3/);
assert.match(html, /bukan diagram rangkaian atau panduan wiring/);
assert.ok(html.indexOf("Satu alat. Proses yang bisa") < html.indexOf("Dari alat ke"), "Skema mengikuti About");
assert.match(html, /id="komponen"/);
assert.match(html, /Bagian penting di balik/);
assert.match(html, /model sensor dan rincian rangkaian menunggu dokumentasi final/);
assert.ok(html.indexOf("Dari alat ke") < html.indexOf("Bagian penting di balik"), "Komponen mengikuti skema");
assert.match(html, /id="faq"/);
assert.equal((html.match(/<details\b/g) ?? []).length, 4, "FAQ berisi empat pertanyaan native");
assert.match(html, /Landing page terbuka untuk umum, sedangkan dashboard hanya untuk admin/);
assert.ok(html.indexOf("Bagian penting di balik") < html.indexOf("Pertanyaan yang sering"), "FAQ mengikuti komponen");
assert.doesNotMatch(html, /ArrowDownRight|ArrowUpRight/);
assert.doesNotMatch(html, /Sobers|Days Sober|App Store/);
const image = await fetch(`${origin}/images/login-hero.webp`);
assert.equal(image.status, 200, "Foto hero harus tersedia");
console.log("Hero, About, skema konseptual, komponen, FAQ, foto, dan akses admin: OK");
